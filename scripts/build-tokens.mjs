// Generates src/design/tokens.css from src/design/tokens.json (W3C DTCG format).
// Run: npm run tokens
//
// Output mapping:
//   theme.light.*  -> :root               --<name>
//   theme.dark.*   -> [data-theme="dark"] --<name>
//   everything else -> :root             --<group>-<path>   (e.g. --radius-pill, --font-size-body)
// layout.* drops its group prefix (--nav-h, --sidebar-w) to keep existing variable names.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(join(root, 'src/design/tokens.json'), 'utf8'))

const isToken = v => v && typeof v === 'object' && '$value' in v

function flatten(node, path = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue
    if (isToken(v)) out.push([[...path, k], v.$value])
    else if (v && typeof v === 'object') flatten(v, [...path, k], out)
  }
  return out
}

const decl = ([path, value]) => `  --${path.join('-')}: ${value};`

const { theme, layout, ...globals } = tokens
const base = [
  ...flatten(globals).map(decl),
  ...flatten(layout).map(decl),
  ...flatten(theme.light).map(decl),
]
const dark = flatten(theme.dark).map(decl)

const css = `/* GENERATED by scripts/build-tokens.mjs from src/design/tokens.json — do not edit by hand. */
:root {
${base.join('\n')}
}

[data-theme="dark"] {
${dark.join('\n')}
}
`
writeFileSync(join(root, 'src/design/tokens.css'), css)
console.log(`tokens.css: ${base.length} base + ${dark.length} dark variables`)
